"""Снятие водяного знака Veo накладкой.

Проверка идёт от обратного: кадр смешивается со знаком по той же формуле, по
которой его накладывает генератор, и дальше спрашивается, вернётся ли кадр
как был. Так ловятся обе ошибки, из-за которых накладка когда-то оставляла
призрак: промах по месту и заниженная сила.
"""
from __future__ import annotations

import pytest

np = pytest.importorskip("numpy")

from vidpipe import veo

СИЛА = 0.24          # пик альфы, с которым знак кладётся в пробный кадр
W, H = 480, 270


def фон(семя: int = 7):
    """Кадр под знак: крупные пятна и лёгкое зерно, как в готовом клипе.

    На ровной заливке верна любая правка, поэтому фон неоднородный. Но и
    мелкой мешанины тут быть не должно: в углу настоящего кадра её не
    бывает, а связь с профилем она сбивает сильнее, чем сам знак.
    """
    ш = np.random.default_rng(семя)
    пятна = ш.integers(40, 190, size=(H//45 + 2, W//45 + 2, 3)).astype(np.float32)
    к = np.repeat(np.repeat(пятна, 45, axis=0), 45, axis=1)[:H, :W]
    for _ in range(3):                      # растушевать стыки пятен
        к = (к + np.roll(к, 7, axis=0) + np.roll(к, 7, axis=1))/3
    return np.clip(к + ш.normal(0, 2.0, к.shape), 0, 255).astype(np.uint8)


def место_знака():
    п = veo.профили()["23x10"]
    в, ш = п.shape
    спр, сн = veo.ОТСТУПЫ["23x10"]
    return {"профиль": "23x10", "x": W-спр-ш, "y": H-сн-в,
            "ширина": ш, "высота": в, "карта": п}


def со_знаком(картинка, сила=СИЛА):
    """Как кладёт генератор: alpha*белое + (1-alpha)*кадр."""
    м = место_знака()
    a = np.clip(м["карта"]*сила, 0, 0.99)[..., None]
    y, x, в, ш = м["y"], м["x"], м["высота"], м["ширина"]
    вых = картинка.copy()
    уч = картинка[y:y+в, x:x+ш].astype(np.float32)
    вых[y:y+в, x:x+ш] = np.clip(a*255 + (1-a)*уч, 0, 255).round().astype(np.uint8)
    return вых


def пробы(сила=СИЛА, семена=(1, 2, 3, 4, 5)):
    return [со_знаком(фон(с), сила) for с in семена]


def test_профили_на_месте():
    """Без ассета накладка молча превратилась бы в затирание."""
    п = veo.профили()

    assert set(п) == {"23x10", "68x30", "99x43"}
    assert п["23x10"].shape == (10, 23)
    assert п["23x10"].max() == pytest.approx(1.0)


def test_место_знака_находится_точно():
    """Промах на пиксель оставляет по краю букв светлую обводку."""
    ждём = место_знака()

    найдено = veo.найти(пробы())

    assert найдено["уверенно"]
    assert найдено["профиль"] == "23x10"
    assert (найдено["x"], найдено["y"]) == (ждём["x"], ждём["y"])


def test_сила_считается_по_кадру():
    """Сила знака не константа: 0.18 из чужого проекта нам занижена."""
    место = veo.найти(пробы())

    с = veo.сила(пробы(), место)

    assert с == pytest.approx(СИЛА, rel=0.15)


def test_кадр_возвращается_как_был():
    чистые = [фон(с) for с in (1, 2, 3)]
    грязные = [со_знаком(к) for к in чистые]
    место = veo.найти(грязные)
    с = veo.сила(грязные, место)
    y, x, в, ш = место["y"], место["x"], место["высота"], место["ширина"]

    было = np.abs(грязные[0][y:y+в, x:x+ш].astype(float)
                  - чистые[0][y:y+в, x:x+ш].astype(float)).mean()
    стало = np.abs(veo.снять(грязные[0], место, с)[y:y+в, x:x+ш].astype(float)
                   - чистые[0][y:y+в, x:x+ш].astype(float)).mean()

    assert было > 8            # знак действительно был виден
    assert стало < было/4      # и его почти не осталось


def test_после_правки_остаток_ниже_порога():
    """Порог остатка — то, чем команда решает, не звать ли затирание."""
    грязные = пробы()
    место = veo.найти(грязные)
    с = veo.сила(грязные, место)

    ост = veo.остаток([veo.снять(к, место, с) for к in грязные], место)

    assert abs(ост) < veo.ОСТАТОК


def test_на_чистом_кадре_знак_не_мерещится():
    """Ложная находка хуже пропуска: она правит нетронутый угол."""
    найдено = veo.найти([фон(с) for с in (1, 2, 3, 4, 5)])

    assert not найдено["уверенно"]


def test_без_знака_команда_зовёт_затирание():
    """Откат должен быть слышен: подмена приёма молча — это брак вслепую."""
    pytest.importorskip("cv2")
    from vidpipe.marks import затереть_знак, приём_знака

    как, что = приём_знака([фон(1), фон(2), фон(3)])

    assert как is затереть_знак
    assert "затиранием" in что


def test_со_знаком_команда_берёт_накладку():
    pytest.importorskip("cv2")
    from vidpipe.marks import затереть_знак, приём_знака

    как, что = приём_знака(пробы())

    assert как is not затереть_знак
    assert "сила накладки" in что


def test_заданную_силу_остаток_не_отменяет():
    """--альфа задают, чтобы снять знак наполовину; заплатка тут не помощь."""
    pytest.importorskip("cv2")
    from vidpipe.marks import затереть_знак, приём_знака

    как, что = приём_знака(пробы(), альфа=0.10)

    assert как is not затереть_знак


def test_слабый_знак_не_перетирается():
    """Пересчёт силы вверх выел бы под буквами тёмный след."""
    грязные = пробы(сила=0.10)
    место = veo.найти(грязные)

    с = veo.сила(грязные, место)

    assert с == pytest.approx(0.10, rel=0.2)
