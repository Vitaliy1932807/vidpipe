"""Шаг 0: тема -> dossier.md — досье фактов перед сценарием.

Первое звено конвейера. Сценарий пишется не из головы, а из досье: редкие
факты, источники, факт-переворот. Раньше промпт копировался в чат руками,
теперь он лежит в канале как `research.md` и работает командой.

Про честность фактов. Шаг не ходит в интернет: он спрашивает модель, а та
отвечает из того, что помнит. Для дат, цифр и имён этого мало — методика
канала требует проверяемости. Поэтому досье помечается как черновик и просит
сверки, а не выдаётся за источник.
"""
from __future__ import annotations

from ..config import env_int, read_prompt, read_text
from ..llm import complete

ЗАПАСНОЙ = """Ты — исследователь для документального ролика. По теме собери
досье: редкие проверяемые факты, даты, имена, цифры, свидетельства очевидцев,
конкурирующие версии и то, что осталось невыясненным.

Отдельно выдели факт-переворот: деталь, которая меняет привычную картину
события.

Для каждого факта укажи, насколько ты в нём уверен и что нужно проверить по
первоисточнику. Не заполняй пробелы красивыми догадками: «данных нет» — это
нормальный ответ, выдуманная дата — нет."""

ШАПКА = """<!-- Черновик досье. Модель отвечала по памяти, без выхода в
интернет: даты, цифры и имена сверь по первоисточникам, прежде чем они уедут
в сценарий. Методика канала требует проверяемости фактов. -->

"""


def run(project, force: bool = False) -> None:
    досье = project.dir / "dossier.md"
    if досье.exists() and not force:
        print(f"[research] пропуск, {досье.name} уже есть")
        return
    if not project.prompt.exists():
        raise SystemExit(
            f"[research] нет {project.prompt.name} — сначала задай тему:\n"
            f"  vidpipe init --topic \"твоя тема\" --dir {project.dir}"
        )

    система, источник = read_prompt(project, "research.md")
    print(f"[research] промпт: {источник or 'встроенный'}")

    тема = read_text(project.prompt)
    текст = complete(система or ЗАПАСНОЙ, тема,
                     max_tokens=env_int("RESEARCH_MAX_TOKENS", 8000))
    досье.write_text(ШАПКА + текст.strip() + "\n", encoding="utf-8")

    print(f"[research] {досье.name}: {len(текст.split())} слов")
    print("[research] сверь даты, цифры и имена по первоисточникам — "
          "модель отвечала по памяти")
