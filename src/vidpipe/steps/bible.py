"""Шаг: script.md -> bible.md — постоянные описания героев, предметов и мест.

Генератор видео не помнит предыдущий кадр. Если в одной сцене написать
«мужчина средних лет», в другой «мужчина в кабине», а в третьей «человек с
фонарём», он нарисует трёх разных людей — и ролик развалится на набор
несвязанных кадров.

Поэтому описание героя пишется один раз, получает постоянный идентификатор
и дальше подставляется в каждую сцену, где он есть. То же с предметами:
мотовоз, журнал, телогрейка должны выглядеть одинаково от кадра к кадру.

Файл рассчитан на правку руками — модель делает черновик, человек доводит.
"""
from __future__ import annotations

import re

from ..config import read_text
from ..llm import complete_json

SYSTEM = """Ты составляешь визуальную библию для документального ролика,
который будет целиком сгенерирован нейросетью по кадрам.

Задача: выписать постоянные описания людей, предметов и мест, которые
появляются в сценарии больше одного раза. Генератор не помнит предыдущий
кадр, поэтому описание должно быть настолько точным, чтобы по нему дважды
получился один и тот же человек.

Для каждого человека укажи по-английски: пол, возраст, тип внешности,
форму лица, волосы, растительность на лице, брови, кожу, глаза, рост,
одежду целиком (верх, низ, обувь, головной убор). Одежда постоянная:
добавь фразу о том, что она не меняется между сценами.

Для предметов и мест: материал, возраст, износ, цвет, размер, характерные
детали. Столько, чтобы предмет узнавался.

ЗАПРЕЩЕНО описывать необъяснимое: голос, фигуру, того, кто считает, следы
неизвестного происхождения. Это остаётся неизвестным по замыслу, и
описывать его нельзя даже здесь.

Идентификаторы — латиницей, заглавными, с подчёркиванием: PETR_01,
MOTOVOZ_01, DEPOT_01.

Верни JSON:
{"characters": [{"id": "PETR_01", "description": "Male, 52 years old. ..."}],
 "objects": [{"id": "MOTOVOZ_01", "description": "A small narrow-gauge ..."}]}

Описание — одна строка, английский, без переводов строки."""

ЗАГОЛОВОК = """# Визуальная библия ролика

Постоянные описания героев и предметов. Подставляются в каждую сцену, где
они есть, чтобы генератор не рисовал в каждом кадре нового человека.

Правь руками: модель делает черновик, но именно от точности этих строк
зависит, соберётся ролик в одну историю или рассыплется.

Формат: внутри блока — запись на абзац. Первая строка абзаца это
идентификатор заглавными латинскими, дальше описание по-английски.

Того, что по замыслу остаётся неизвестным — голос, фигуру, того, кто
считает, — сюда вписывать нельзя. Описанная загадка перестаёт быть загадкой.
"""

ID = re.compile(r"^[A-Z][A-Z0-9_]*$")


def parse(text: str) -> dict[str, dict[str, str]]:
    """Разбираем bible.md в {"CHARACTERS": {ID: описание}, "OBJECTS": {...}}."""
    итог: dict[str, dict[str, str]] = {}
    for m in re.finditer(r"^\[([A-Z]+)\]\s*\n(.*?)(?=^\[[A-Z]+\]|\Z)", text, re.S | re.M):
        записи: dict[str, str] = {}
        for кусок in re.split(r"\n\s*\n", m.group(2).strip()):
            строки = [s.strip() for s in кусок.splitlines() if s.strip()]
            if len(строки) >= 2 and ID.match(строки[0]):
                записи[строки[0]] = " ".join(строки[1:])
        итог[m.group(1)] = записи
    return итог


def load(project) -> dict[str, dict[str, str]]:
    """Библия ролика, если она есть. Ищется по обычной цепочке ресурсов."""
    try:
        path = project.resource("bible.md")
    except SystemExit:
        return {}
    print(f"[bible] библия: {path} ({project.resource_source('bible.md')})")
    return parse(read_text(path))


def render(данные: dict) -> str:
    части = [ЗАГОЛОВОК]
    for блок, ключ in (("CHARACTERS", "characters"), ("OBJECTS", "objects")):
        части.append(f"[{блок}]")
        for запись in данные.get(ключ, []):
            иден = str(запись.get("id", "")).strip()
            описание = " ".join(str(запись.get("description", "")).split())
            if иден and описание:
                части.append(f"{иден}\n{описание}\n")
    return "\n".join(части).rstrip() + "\n"


def run(project, force: bool = False) -> None:
    if not project.script.exists():
        raise SystemExit(f"[bible] нет {project.script.name} — сначала шаг script")
    if project.bible.exists() and not force:
        print(f"[bible] пропуск, {project.bible.name} уже есть")
        return

    данные = complete_json(SYSTEM, read_text(project.script)[:20000], max_tokens=4000)
    project.bible.write_text(render(данные), encoding="utf-8")

    разобрано = parse(read_text(project.bible))
    print(f"[bible] {project.bible.name}: "
          f"героев {len(разобрано.get('CHARACTERS', {}))}, "
          f"предметов {len(разобрано.get('OBJECTS', {}))}")
    print("[bible] вычитай файл руками: от точности описаний зависит, "
          "будет ли это один человек во всех кадрах")
