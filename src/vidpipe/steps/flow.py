# Но не всякое слово на -men человек, и эти встречаются в наших же кадрах:
# specimen в музее, bitumen на путях, lumen в описании света.
НЕ_ЛЮДИ = {"specimen", "specimens", "bitumen", "regimen", "regimens",
           "lumen", "lumens", "abdomen", "omen", "omens", "acumen",
           "talisman", "ottoman", "ottomans", "cyclamen", "ramen"}
_НА_MAN = re.compile(_ГРАНИЦА + r"(\w+m[ae]n)" + _ГРАНИЦА, re.I)


def есть_люди(текст: str) -> bool:
    """Есть ли в промпте человек. Слово целиком, а не кусок другого слова."""
    текст = текст or ""
    if _ЛЮДИ.search(текст):
        return True
    return any(с.lower() not in НЕ_ЛЮДИ for с in _НА_MAN.findall(текст))
# Сплошные запреты людей, и только они. Уточнённый запрет вида
# "no person in the doorway" снимать нельзя: он про другого человека, не про
# рассказчика, и держит главную тайну ролика.
# Слова, которыми модель обозначает человека вообще.
ЛЮДИ_В_ЗАПРЕТЕ = {"person", "persons", "people", "human", "humans",
                  "figure", "figures", "one", "man", "woman", "men", "women"}


def запрет_людей(фраза: str) -> bool:
    """Запрет людей вообще — не человека в конкретном месте кадра.

    Список точных фраз здесь уже стоял и протёк: "no visible figure" в него
    не попал, и девять сцен уехали с описанием героя и запретом фигуры разом.
    Поэтому смотрим не на строку целиком, а на её устройство: "no" плюс одно
    слово о людях. "no person in the doorway" остаётся — это указание, где
    людей быть не должно, и оно законно.
    """
    слова = фраза.lower().strip().rstrip(".").split()
    if len(слова) < 2 or слова[0] != "no":
        return False
    слова = [с for с in слова[1:] if с != "visible"]
    if слова[-2:] == ["in", "frame"]:
        слова = слова[:-2]
    return len(слова) == 1 and слова[0] in ЛЮДИ_В_ЗАПРЕТЕ


def собрать(сцена: dict, глобальное: dict) -> str:
    """Готовый текст одного кадра для вставки в Flow.

    Здесь же снимается противоречие, которое модель создаёт постоянно: она
    приписывает сцене героя и одновременно запрещает людей в кадре. Смотрим
    на сам промпт. Есть в нём человек — подставляем описание и убираем запрет.
    Нет — выбрасываем описание, потому что описывать некого.

    Проверка на человека касается только людей. Предметы подставляются всегда:
    молоток остаётся тем же молотком, а журнал тем же журналом, есть рядом
    человек или нет. Раньше отбрасывалось всё разом, и половина библии — весь
    раздел предметов — молча не доезжала до кадров, где людей нет. Ровно ради
    таких кадров она и заводилась: чтобы кабина, полоса и журнал выглядели
    одинаково во всём ролике.
    """
    герои = глобальное.get("characters", {})
    предметы = глобальное.get("objects", {})
    промпт = сцена.get("prompt", "").rstrip(". ")
    есть_человек = есть_люди(промпт)

    названные = сцена.get("characters", [])
    описания = [предметы[и] for и in названные if и in предметы]
    свои_герои = [герои[и] for и in названные if и in герои]
    if есть_человек:
        описания = свои_герои + описания

    свой_запрет = сцена.get("negative", "")
    if есть_человек and свои_герои:
        свой_запрет = ", ".join(
            ч.strip() for ч in свой_запрет.split(",")
            if ч.strip() and not запрет_людей(ч))

    куски = [промпт]
    if описания:
        куски.append(" ".join(о.rstrip(". ") for о in описания))
    for поле in ("camera", "lighting", "continuity"):
        if сцена.get(поле):
            куски.append(сцена[поле].rstrip(". "))
    for поле in ("style", "environment"):
        if глобальное.get(поле):
            куски.append(глобальное[поле].rstrip(". "))
    запреты = ", ".join(x for x in (глобальное.get("negative", ""),
                                    свой_запрет) if x)
    if запреты:
        куски.append(запреты)
    return ". ".join(к for к in куски if к) + "."


def render_txt(глобальное: dict, сцены: list[dict], вид: str) -> str:
    """Только промпты одного вида, по одному на сцену, без разметки.

    Генераторы видео и картинок разные, и работают с ними подряд: открыл файл,
    взял блок, вставил. Разметка, заголовки и отступы в этом месте мешают —
    их приходится вычищать руками при каждой вставке. Поэтому здесь номер
    сцены отдельной строкой и промпт одной строкой, больше ничего.
    """
    строки = []
    for с in сцены:
        если = с.get("kind") or вид_кадра(с)
        if если != вид:
            continue
        строки.append(str(с["scene"]))
        строки.append(собрать(с, глобальное))
        строки.append("")
    return "\n".join(строки)


def разложить_по_виду(project, глобальное: dict, сцены: list[dict]) -> dict:
    """Пишет рядом с выпуском два файла: промпты видео и промпты картинок."""
    сделано = {}
    for вид, имя in (("видео", "промпты-видео.txt"),
                     ("картинка", "промпты-картинки.txt")):
        текст = render_txt(глобальное, сцены, вид)
        сколько = sum(1 for с in сцены if (с.get("kind") or вид_кадра(с)) == вид)
        путь = project.dir / имя
        путь.write_text(текст, encoding="utf-8")
        сделано[вид] = (путь, сколько)
    return сделано


def render_md(project, глобальное: dict, сцены: list[dict]) -> str:
    строки = [f"# Промпты для Flow — {project.name}", ""]
    итого = sum(с["duration"] for с in сцены)
    видео = sum(1 for с in сцены if (с.get("kind") or вид_кадра(с)) == "видео")
    строки.append(f"{итого:.0f} секунд, {len(сцены)} сцен: {видео} видео и "
                  f"{len(сцены) - видео} картинок. "
                  f"Стиль, окружение и запреты уже внутри каждого блока — "
                  f"копируй блок целиком.")
    строки.append("")
    for с in сцены:
        вид = с.get("kind") or вид_кадра(с)
        строки.append(f"## {с['scene']} · {с['start']}–{с['end']} "
                      f"({с['duration']:.0f} с) · {вид.upper()} — "
                      f"{с.get('purpose', '')}")
        строки.append("")
        строки.append("```")
        строки.append(собрать(с, глобальное))
        строки.append("```")
        if с.get("audio"):
            строки.append(f"звук: {с['audio']}")
        строки.append("")
    return "\n".join(строки)


