"""Разбор папки clips: какой файл какой сцене принадлежит.

Генератор отдаёт клипы под своими именами и нумерует их подряд, по порядку
генерации. Сборка же сопоставляет кадры со сценами по первому числу в имени.
Пока сцены снимают подряд, это совпадает. Стоит пропустить хоть одну, и
нумерация разъезжается молча.

Живой случай: в готовой папке файл 037 содержал 56-ю сцену, остывший очаг из
финала. Собранное видео разошлось бы с голосом почти целиком, и по логам это
было бы не видно.

Поэтому файл опознаётся не по номеру, а по содержанию: генератор оставляет в
имени начало промпта, и по нему кадр однозначно находит свою сцену.
"""
from __future__ import annotations

import json
import re

from .config import env, read_text

ВИДЕО = {".mp4", ".mov", ".webm", ".mkv"}
КАРТИНКИ = {".png", ".jpg", ".jpeg", ".webp"}
СТОП = {"a", "an", "the", "of", "in", "on", "with", "and", "to", "at", "from",
        "into", "over", "under", "for", "its", "his", "her", "their"}


def слова(текст: str) -> set[str]:
    return {с for с in re.sub(r"[^a-zA-Z]+", " ", текст).lower().split()
            if с not in СТОП and len(с) > 2}


def слаг(имя: str) -> set[str]:
    """Слова из имени файла без ведущего номера и хвостового идентификатора."""
    без_номера = re.sub(r"^\d+[-_]?", "", имя)
    без_хвоста = re.sub(r"[-_]\d+$", "", без_номера)
    return слова(без_хвоста)


def номер_в_имени(имя: str) -> int | None:
    m = re.search(r"\d+", имя)
    return int(m.group()) if m else None


def файлы_папки(папка):
    """Все кадры, включая вложенные папки.

    Генератор отдаёт партию архивом, и она разворачивается в подпапку с
    именем вроде «1». Кадры при этом настоящие и на месте, а сборка их не
    видит: она смотрит только верхний уровень. Поэтому ищем вглубь, а при
    переименовании поднимаем наверх.
    """
    return sorted((f for f in папка.rglob("*")
                   if f.is_file() and f.suffix.lower() in ВИДЕО | КАРТИНКИ),
                  key=lambda f: (f.parent != папка, f.name))


def сопоставить(файлы, сцены: list[dict], порог: float = 0.5) -> dict:
    """Кому какая сцена. Возвращает разбор, ничего не трогая на диске.

    Сцена занимается один раз: два файла на одну сцену это ошибка, а не выбор.
    """
    промпты = {с["scene"]: слова(с.get("prompt") or "") for с in сцены}
    вид = {с["scene"]: с.get("kind", "") for с in сцены}

    пары, занятые, безымянные = [], set(), []
    for f in файлы:
        мой = слаг(f.stem)
        лучший, балл = None, 0.0
        for n, п in промпты.items():
            if n in занятые or not мой:
                continue
            доля = len(мой & п) / len(мой)
            if доля > балл:
                лучший, балл = n, доля
        if лучший and балл >= порог:
            занятые.add(лучший)
            пары.append({"файл": f.name, "путь": f, "сцена": лучший,
                         "совпадение": round(балл, 2),
                         "тип": "видео" if f.suffix.lower() in ВИДЕО else "картинка",
                         "номер_в_имени": номер_в_имени(f.stem)})
        else:
            безымянные.append(f.name)

    номера = [п["сцена"] for п in пары]
    return {
        "пары": пары,
        "без_совпадения": безымянные,
        "по_порядку": номера == sorted(номера),
        "нет_клипа": sorted({с["scene"] for с in сцены} - занятые),
        "вид": вид,
    }


def cmd_clips(args) -> None:
    from .config import Project

    project = Project.load(args.dir)
    папка = project.dir / env("CLIPS_DIR", "clips")
    if not папка.is_dir():
        raise SystemExit(f"[clips] нет папки {папка}")
    if not project.flow.exists():
        raise SystemExit(f"[clips] нет {project.flow.name} — сначала шаг flow")

    сцены = json.loads(read_text(project.flow)).get("scenes") or []
    файлы = файлы_папки(папка)
    if not файлы:
        raise SystemExit(f"[clips] в {папка.name} нет ни видео, ни картинок")

    разбор = сопоставить(файлы, сцены)
    видео = sum(1 for п in разбор["пары"] if п["тип"] == "видео")
    print(f"[clips] файлов {len(файлы)}: {видео} видео, "
          f"{len(разбор['пары']) - видео} картинок, сцен в ролике {len(сцены)}")

    переименовать = [п for п in разбор["пары"]
                     if п["номер_в_имени"] != п["сцена"]
                     or п["путь"].parent != папка]
    if not разбор["по_порядку"]:
        print("[clips] ! порядок файлов не совпадает с порядком сцен, "
              "проверь список глазами")

    for п in разбор["пары"]:
        метка = "  " if п["номер_в_имени"] == п["сцена"] else "->"
        print(f"  {метка} сцена {п['сцена']:>3} {п['тип']:8} {п['файл'][:52]}")

    if разбор["без_совпадения"]:
        print(f"[clips] не опознаны, номер возьмётся из имени: "
              f"{', '.join(разбор['без_совпадения'][:5])}")

    нет = разбор["нет_клипа"]
    if нет:
        по_виду = {}
        for n in нет:
            по_виду.setdefault(разбор["вид"].get(n) or "не помечено", []).append(n)
        print(f"[clips] не хватает {len(нет)} сцен:")
        for вид, номера in по_виду.items():
            print(f"  {вид:9} {', '.join(str(n) for n in номера)}")
    else:
        print("[clips] все сцены закрыты")

    if not args.apply:
        if переименовать:
            print(f"[clips] переименовать нужно {len(переименовать)} файлов, "
                  f"это сухой прогон. Применить: vidpipe clips --apply")
        return

    if not переименовать:
        print("[clips] переименовывать нечего")
        return

    карта = папка / "карта-переименования.json"
    прежняя = json.loads(read_text(карта)) if карта.exists() else []
    for п in переименовать:
        старый = п["путь"]
        хвост = re.sub(r"^\d+[-_]?", "", старый.stem)
        новый = папка / f"{п['сцена']:03d}-{хвост}{старый.suffix}"
        if новый.exists():
            print(f"[clips] ! {новый.name} уже есть, пропускаю {старый.name}")
            continue
        старый.rename(новый)
        прежняя.append({"было": п["файл"], "стало": новый.name, "сцена": п["сцена"]})
    карта.write_text(json.dumps(прежняя, ensure_ascii=False, indent=1),
                     encoding="utf-8")
    print(f"[clips] переименовано {len(переименовать)}, прежние имена в {карта.name}")
