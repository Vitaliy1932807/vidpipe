"""Водяной знак Veo: снять накладку, а не замазать угол.

Знак не нарисован поверх кадра, он в него вмешан:

    кадр_со_знаком = α·белое + (1-α)·кадр

Значит кадр возвращается точно: `(кадр_со_знаком - α·255)/(1-α)`. Под знаком
оказывается настоящая картинка, а не заплатка. Затирание тот же угол просто
замазывает соседними пикселями: на спокойном фоне это незаметно, на движении
и на мелкой фактуре в углу остаётся мыло, и оно живёт все восемь секунд.

Здесь это уже пробовали и получили призрак — отсюда старая запись в marks.py,
что накладка не берёт. Причина была не в приёме, а в двух местах рядом с ним:

  профиль    альфа снималась на глаз с одного кадра и занижалась. Профиль
             знака взят готовый: 23x10, 68x30, 99x43 — обмер настоящих
             выпусков Veo из gemini-watermark-remover (src/video/
             veoTextWatermarkTemplates.js). Наш угол 1280x720 — ровно
             23x10 с отступами 15 и 16, совпало до пикселя.

  место      знак искали по долям кадра. Доли врут на другом разрешении и
             на другой раскладке: место ищется корреляцией профиля с
             яркостью по нескольким пробам, и берётся то, за которое
             проголосовало большинство проб.

Сила накладки не константа: она считается из самого кадра наклоном яркости
по профилю знака. Константа 0.18 из чужого проекта на наших клипах даёт
недобор, ровно тот самый призрак.
"""
from __future__ import annotations

from pathlib import Path

from .config import PACKAGE_ASSETS

# id профиля -> отступ справа, отступ снизу (пиксели, как в выпусках Veo)
ОТСТУПЫ = {"23x10": (15, 16), "68x30": (44, 48), "99x43": (64, 68)}

ПОРОГ_СВЯЗИ = 0.62      # NCC ниже — это не знак, а что-то своё в углу
ДОЛЯ_ГОЛОСОВ = 0.6      # место должно выиграть на большинстве проб
АКТИВНЫЕ = 0.02         # профиль ниже — фон шаблона, в счёт не идёт
ШУМ = 3/255             # квантование: такую альфу трогать нечего
ПРЕДЕЛ_АЛЬФЫ = 0.9      # выше — деление на почти ноль
ОСТАТОК = 0.03          # остаточная сила после правки, выше — не сработало


def профили() -> dict:
    """Профили знака: имя -> массив (высота, ширина) в долях от пика."""
    import numpy as np
    ф = PACKAGE_ASSETS / "veo_text.npz"
    if not ф.exists():
        return {}
    с = np.load(ф)
    return {и: с[и].astype(np.float32) for и in с.files}


def яркость(картинка):
    """Яркость 0..255. Порядок каналов у cv2 — BGR, отсюда веса задом."""
    import numpy as np
    к = картинка.astype(np.float32)
    return 0.0722*к[..., 0] + 0.7152*к[..., 1] + 0.2126*к[..., 2]


def _связь(я, проф, маска, x: int, y: int) -> float:
    """NCC яркости с профилем по его же штрихам, без фона шаблона."""
    import numpy as np
    в, ш = проф.shape
    уч = я[y:y+в, x:x+ш]
    if уч.shape != проф.shape:
        return 0.0
    a = уч[маска]
    b = проф[маска]
    if a.size < 2:
        return 0.0
    a = a - a.mean()
    b = b - b.mean()
    зн = float(np.sqrt((a*a).sum() * (b*b).sum()))
    return float((a*b).sum() / зн) if зн > 0 else 0.0


def места(W: int, H: int, проф: dict) -> list[tuple]:
    """Куда вообще может попасть знак: угол плюс небольшой разброс отступов."""
    вых = []
    for и, п in проф.items():
        в, ш = п.shape
        if ш > W or в > H:
            continue
        r = max(4, round(min(ш, в)*0.35))
        оx, оy = ОТСТУПЫ.get(и, (round(ш*0.65), round(в*1.6)))
        for спр in range(max(0, оx-r), min(W-ш, оx+r)+1):
            for сн in range(max(0, оy-r), min(H-в, оy+r)+1):
                вых.append((и, W-спр-ш, H-сн-в))
    return вых


def найти(кадры) -> dict | None:
    """Место знака по нескольким пробам: голосование, а не одна проба.

    Фон под знаком меняется, и на отдельном кадре знак может утонуть совсем.
    Поэтому место выбирается не лучшим кадром, а большинством: кандидат,
    выигравший меньше чем на шести пробах из десяти, отвергается.
    """
    import numpy as np
    проф = профили()
    if not проф or not len(кадры):
        return None
    маски = {и: п > АКТИВНЫЕ for и, п in проф.items()}
    H, W = кадры[0].shape[:2]
    кандидаты = места(W, H, проф)
    if not кандидаты:
        return None
    голоса = {к: 0 for к in кандидаты}
    оценки = {к: [] for к in кандидаты}
    for кадр in кадры:
        я = яркость(кадр)
        лучший, лучшая = None, -2.0
        for к in кандидаты:
            и, x, y = к
            с = _связь(я, проф[и], маски[и], x, y)
            оценки[к].append(с)
            if с > лучшая:
                лучший, лучшая = к, с
        if лучший is not None:
            голоса[лучший] += 1
    к = max(кандидаты, key=lambda z: (голоса[z], float(np.mean(оценки[z]))))
    и, x, y = к
    в, ш = проф[и].shape
    доля = голоса[к]/len(кадры)
    средняя = float(np.mean(оценки[к]))
    лучшая = float(np.max(оценки[к]))
    свой_угол = (W-x-ш, H-y-в) == ОТСТУПЫ.get(и)
    # Знак на пёстром углу связь занижает: фон шумит сильнее самих букв.
    # Тогда за него говорит постоянство — своё штатное место и голоса почти
    # всех проб, при хотя бы одной пробе с полной связью.
    тихий = (свой_угол and доля >= 0.8 and лучшая >= ПОРОГ_СВЯЗИ
             and средняя >= ПОРОГ_СВЯЗИ*0.68)
    return {"профиль": и, "x": x, "y": y, "ширина": ш, "высота": в,
            "связь": средняя, "лучшая": лучшая, "доля": доля,
            "карта": проф[и],
            "уверенно": (средняя >= ПОРОГ_СВЯЗИ and доля >= ДОЛЯ_ГОЛОСОВ)
                        or тихий}


def сила(кадры, место) -> float | None:
    """Сила накладки из самого кадра: наклон яркости по профилю знака.

    Под знаком яркость поднята на α·(255 - фон). Профиль знака известен,
    фон берётся по пикселям вне штрихов — остаётся поделить одно на другое.
    Медиана по пробам, потому что на светлом фоне знак почти не виден и
    оценка там шумит.
    """
    import numpy as np
    п = место["карта"]
    маска = п > АКТИВНЫЕ
    x, y, ш, в = место["x"], место["y"], место["ширина"], место["высота"]
    оценки = []
    for кадр in кадры:
        уч = яркость(кадр)[y:y+в, x:x+ш]
        if уч.shape != п.shape:
            continue
        фон = float(уч[~маска].mean()) if (~маска).any() else float(уч.mean())
        if 255.0 - фон < 20.0:       # белая стена: знака на ней не видно
            continue
        d = п - п.mean()
        разброс = float((d*d).sum())
        if разброс <= 0:
            continue
        наклон = float(((уч - уч.mean())*d).sum() / разброс)
        оценки.append(наклон / (255.0 - фон))
    if not оценки:
        return None
    return float(np.clip(np.median(оценки), 0.0, ПРЕДЕЛ_АЛЬФЫ))


def снять(картинка, место, сила_накладки: float):
    """Обратное альфа-смешение по профилю знака."""
    import numpy as np
    п = место["карта"]
    x, y, ш, в = место["x"], место["y"], место["ширина"], место["высота"]
    H, W = картинка.shape[:2]
    if x < 0 or y < 0 or x+ш > W or y+в > H or сила_накладки <= 0:
        return картинка
    альфа = np.clip(п*сила_накладки, 0.0, ПРЕДЕЛ_АЛЬФЫ)
    работа = (np.maximum(0.0, альфа - ШУМ) > 0.002)
    if not работа.any():
        return картинка
    уч = картинка[y:y+в, x:x+ш].astype(np.float32)
    a = альфа[..., None]
    чисто = np.clip((уч - a*255.0) / (1.0 - a), 0, 255)
    вых = картинка.copy()
    вых[y:y+в, x:x+ш] = np.where(работа[..., None], чисто, уч).round().astype(
        картинка.dtype)
    return вых


def остаток(кадры, место) -> float | None:
    """Сколько знака осталось: та же оценка силы, но после правки."""
    return сила(кадры, место)
