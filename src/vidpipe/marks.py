ЗНАК_ДОЛИ = (1214/1280, 680/720, 1278/1280, 715/720)


# ── чтение и запись ──────────────────────────────────────────────────────
def читать_клип(путь: Path):
    import cv2
    кап = cv2.VideoCapture(str(путь))
    фпс = кап.get(cv2.CAP_PROP_FPS) or 24.0
    кадры = []
    while True:
        ок, к = кап.read()
        if not ок:
            break
        кадры.append(к)
    кап.release()
    return кадры, фпс


def записать_клип(кадры, фпс: float, куда: Path) -> None:
    H, W = кадры[0].shape[:2]
    п = subprocess.Popen([ffmpeg_bin(), "-hide_banner", "-loglevel", "error",
                          "-y", "-f", "rawvideo", "-pix_fmt", "bgr24",
                          "-s", "%dx%d" % (W, H), "-r", "%.5f" % фпс, "-i", "-",
                          "-c:v", "libx264", "-crf", "17", "-preset", "slow",
                          "-pix_fmt", "yuv420p", "-an", str(куда)],
                         stdin=subprocess.PIPE)
    for к in кадры:
        п.stdin.write(к.tobytes())
    п.stdin.close()
    п.wait()


def записать_картинку(картинка, куда: Path) -> None:
    import cv2
    cv2.imencode(куда.suffix or ".jpeg", картинка,
                 [cv2.IMWRITE_JPEG_QUALITY, 95])[1].tofile(str(куда))


# ── сопровождение ────────────────────────────────────────────────────────
def вести_шаблоном(кадры, обл, поиск: int = 60,
                   масштабы=(0.94, 1.0, 1.07, 1.15, 1.28, 1.45)):
    """Путь рамки по кадрам: шаблон предмета, а не модель движения кадра."""
    import cv2
    H, W = кадры[0].shape[:2]
    ax, ay = int(обл[0]*W), int(обл[1]*H)
    bx, by = int(обл[2]*W), int(обл[3]*H)
    шаб = cv2.cvtColor(кадры[0][ay:by, ax:bx], cv2.COLOR_BGR2GRAY)
    путь, тек = [(ax, ay, bx, by)], (ax, ay, bx, by)
    for к in кадры[1:]:
        сер = cv2.cvtColor(к, cv2.COLOR_BGR2GRAY)
        цx, цy = (тек[0]+тек[2])//2, (тек[1]+тек[3])//2
        лучш = None
        for м in масштабы:
            ш, в = int((bx-ax)*м), int((by-ay)*м)
            if ш < 8 or в < 8:
                continue
            ш0, в0 = max(0, цx-ш//2-поиск), max(0, цy-в//2-поиск)
            ш1, в1 = min(W, цx+ш//2+поиск), min(H, цy+в//2+поиск)
            окно = сер[в0:в1, ш0:ш1]
            т = cv2.resize(шаб, (ш, в), interpolation=cv2.INTER_AREA)
            if окно.shape[0] < в or окно.shape[1] < ш:
                continue
            _, оц, _, поз = cv2.minMaxLoc(
                cv2.matchTemplate(окно, т, cv2.TM_CCOEFF_NORMED))
            if лучш is None or оц > лучш[0]:
                лучш = (оц, ш0+поз[0], в0+поз[1], ш, в)
        if лучш is not None and лучш[0] > 0.45:
            _, x, y, ш, в = лучш
            тек = (x, y, x+ш, y+в)
        путь.append(тек)
    return путь


# ── приёмы ───────────────────────────────────────────────────────────────
def маска_букв(картинка, обл, порог: int = 20, полярность: str = "любые"):
    """Маска штрихов внутри рамки: буквы отличаются от сильно размытого фона."""
    import cv2
    import numpy as np
    H, W = картинка.shape[:2]
    ax, ay = max(0, int(обл[0]*W)), max(0, int(обл[1]*H))
    bx, by = min(W, int(обл[2]*W)), min(H, int(обл[3]*H))
    уч = cv2.cvtColor(картинка[ay:by, ax:bx], cv2.COLOR_BGR2GRAY)
    if уч.size == 0:
        return None
    я = min(max(11, (min(уч.shape)//2)*2+1), 51)
    р = cv2.medianBlur(уч, я).astype(np.int16) - уч.astype(np.int16)
    if полярность == "светлые":
        р = -р
    elif полярность == "любые":
        р = np.abs(р)
    м = (р > порог).astype(np.uint8)*255
    м = cv2.dilate(м, np.ones((5, 5), np.uint8))
    полн = np.zeros((H, W), np.uint8)
    полн[ay:by, ax:bx] = м
    return полн


def затереть(картинка, обл, порог: int = 20, полярность: str = "любые"):
    import cv2
    м = маска_букв(картинка, обл, порог, полярность)
    if м is None or not м.any():
        return картинка
    return cv2.inpaint(картинка, м, 5, cv2.INPAINT_TELEA)


def сгладить(картинка, обл, контраст: float = 0.07, перо: int = 8,
             сила: int = 1):
    """Сжать контраст внутри рамки: буквы тонут, предмет остаётся резким."""
    import cv2
    import numpy as np
    H, W = картинка.shape[:2]
    ax, ay = max(0, int(обл[0]*W)), max(0, int(обл[1]*H))
    bx, by = min(W, int(обл[2]*W)), min(H, int(обл[3]*H))
    if bx-ax < 6 or by-ay < 6:
        return картинка
    п = int(перо)
    рx, рy = max(0, ax-п), max(0, ay-п)
    сx, сy = min(W, bx+п), min(H, by+п)
    уч = картинка[рy:сy, рx:сx].astype(np.float32)
    ш, в = сx-рx, сy-рy
    исх = уч
    if сила > 1:
        мал = cv2.resize(уч, (max(2, ш//сила), max(2, в//сила)),
                         interpolation=cv2.INTER_AREA)
        исх = cv2.resize(мал, (ш, в), interpolation=cv2.INTER_LINEAR)
    основа = cv2.GaussianBlur(исх, (0, 0), max(3.0, min(ш, в)/2.5))
    плоско = np.clip(основа + (исх-основа)*контраст, 0, 255)
    м = np.zeros((в, ш), np.float32)
    м[ay-рy:by-рy, ax-рx:bx-рx] = 1.0
    if п > 0:
        м = cv2.GaussianBlur(м, (0, 0), max(1.0, п/2.0))
    м = м[..., None]
    вых = картинка.copy()
    вых[рy:сy, рx:сx] = np.clip(плоско*м + уч*(1-м), 0, 255).astype(np.uint8)
    return вых


def маска_знака(W: int, H: int):
    import cv2
    import numpy as np
    ф = PACKAGE_ASSETS / "watermark_alpha.npy"
    if not ф.exists():
        return None
    альфа = np.load(ф)
    x0, y0 = int(W*ЗНАК_ДОЛИ[0]), int(H*ЗНАК_ДОЛИ[1])
    x1, y1 = int(W*ЗНАК_ДОЛИ[2]), int(H*ЗНАК_ДОЛИ[3])
    if x1-x0 < 4 or y1-y0 < 4:
        return None
    a = cv2.resize(альфа, (x1-x0, y1-y0), interpolation=cv2.INTER_LINEAR)
    м = np.zeros((H, W), np.uint8)
    м[y0:y1, x0:x1] = (a > 0.03).astype(np.uint8)*255
    k = max(3, (int(round(3*W/1280)) | 1))
    return cv2.dilate(м, np.ones((k, k), np.uint8), iterations=2)


def затереть_знак(картинка):
    """Запасной ход: заплатка по маске знака. Берёт всегда, но мылит угол."""
    import cv2
    H, W = картинка.shape[:2]
    м = маска_знака(W, H)
    if м is None:
        return картинка
    return cv2.inpaint(картинка, м, max(4, int(4*W/1280)), cv2.INPAINT_TELEA)


def приём_знака(пробы, альфа: float | None = None, затиранием: bool = False):
    """Выбрать, чем снимать знак с этого клипа, и сказать почему.

    Накладка возвращает картинку под знаком, затирание её замазывает. Поэтому
    накладка идёт первой, а затирание берётся только когда за накладку нечем
    ручаться: знак не опознан, силу посчитать не из чего или после правки
    остаток на месте. Молчаливого отката нет — способ печатается.

    Заданную руками силу откат не отменяет: её задают, когда хотят снять знак
    наполовину, и подмена такой правки заплаткой была бы не помощью.
    """
    if затиранием:
        return затереть_знак, "знак снимается затиранием: так велено ключом"
    место = veo.найти(пробы)
    if место is None:
        return затереть_знак, "профилей знака нет — снимаю затиранием"
    где = "%s в (%d,%d)" % (место["профиль"], место["x"], место["y"])
    if not место["уверенно"]:
        return затереть_знак, (
            "знак не опознан (%s, связь %.2f на %d%% проб) — снимаю затиранием"
            % (где, место["связь"], round(место["доля"]*100)))
    с = альфа if альфа else veo.сила(пробы, место)
    if not с:
        return затереть_знак, (
            "силу накладки не из чего считать (%s) — снимаю затиранием" % где)
    ост = veo.остаток([veo.снять(к, место, с) for к in пробы], место)
    if ост is not None and ост > veo.ОСТАТОК and not альфа:
        return затереть_знак, (
            "накладка не легла (%s, остаток %.3f) — снимаю затиранием"
            % (где, ост))
    return (lambda к: veo.снять(к, место, с)), (
        "знак %s: связь %.2f, сила накладки %.3f, остаток %.3f"
        % (где, место["связь"], с, ост if ост is not None else 0.0))


def пробы_кадров(кадры, сколько: int = 10):
    """Ровно разбросанные пробы: место знака ищется не по одному кадру."""
    if len(кадры) <= сколько:
        return list(кадры)
    шаг = len(кадры)/сколько
    return [кадры[min(len(кадры)-1, int(i*шаг))] for i in range(сколько)]


# ── команда ──────────────────────────────────────────────────────────────
def _разбор_рамки(текст: str) -> tuple[float, float, float, float]:
    ч = [float(z) for z in текст.replace(" ", "").split(",")]
    if len(ч) != 4:
        raise SystemExit("рамка задаётся четырьмя долями: x0,y0,x1,y1")
    return tuple(ч)  # type: ignore[return-value]


def _сбросить_кэш(файл: Path) -> None:
    """Выкинуть посценный кусок правленого кадра.

    Без этого сборка соберёт фильм из прежних кусков: правка в clips есть, а
    в кадре её нет, и по логам ничего не видно — файл получается тем же по
    размеру. На этом уже потерян час.
    """
    m = re.match(r"^(\d{3})[-_]", файл.name)
    if not m or файл.parent.name != "clips":
        return
    папка = файл.parent.parent
    кэш = папка / ".vidpipe"
    снято = []
    for f in (кэш / ("seg_%s.mp4" % m.group(1)), кэш / "silent.mp4"):
        if f.exists():
            f.unlink()
            снято.append(f.name)
    фильм = папка / "video.mp4"
    if фильм.exists():
        запас = папка / "_до правки"
        запас.mkdir(exist_ok=True)
        куда = запас / "video (до правки надписи).mp4"
        н = 2
        while куда.exists():
            куда = запас / ("video (до правки надписи %d).mp4" % н)
            н += 1
        shutil.move(str(фильм), str(куда))
        снято.append("video.mp4")
    if снято:
        print("снято из кэша: %s — иначе сборка взяла бы прежний кусок"
              % ", ".join(снято))
        print("дальше: vidpipe finish")


def cmd_marks(args) -> None:
    _нужен_cv2()
    import cv2
    import numpy as np
    ф = Path(args.file)
    if not ф.exists():
        raise SystemExit(f"нет файла: {ф}")
    видео = ф.suffix.lower() in ВИДЕО
    запас = ф.parent.parent / "_до правки"

    if args.знак:
        приём, области = "знак", []
    else:
        if not args.box:
            raise SystemExit("нужна рамка: --box x0,y0,x1,y1 (доли кадра) "
                             "или --знак")
        # Рамок может быть несколько. Гонять файл через правку дважды нельзя:
        # каждый проход пережимает видео заново и теряет качество, а в кадре
        # с приборами надписей обычно не одна — шильдик, циферблат, табличка.
        области = [_разбор_рамки(b) for b in args.box]
        приём = args.приём

    снятие = None            # чем снимать знак: решается по самим кадрам

    def правка(картинка, рамка):
        if приём == "знак":
            return снятие(картинка)
        if приём == "затирание":
            return затереть(картинка, рамка, args.порог, args.полярность)
        return сгладить(картинка, рамка, args.контраст, 8, args.сила)

    if not видео:
        и = прочитать_картинку(ф)
        if приём == "знак":
            снятие, что = приём_знака([и], args.альфа, args.затиранием)
            print(что)
        н = и
        for о in области:
            н = правка(н, о)
        if args.проба:
            куда = ф.parent / ("проба-" + ф.name)
            записать_картинку(н, куда)
            print("проба:", куда)
            return
        запас.mkdir(parents=True, exist_ok=True)
        (запас / ф.name).write_bytes(ф.read_bytes())
        записать_картинку(н, ф)
        print("правка внесена, оригинал в", запас)
        _сбросить_кэш(ф)
        return

    кадры, фпс = читать_клип(ф)
    if not кадры:
        raise SystemExit("клип не читается")
    if приём == "знак":
        пути = []
        снятие, что = приём_знака(пробы_кадров(кадры), args.альфа,
                                  args.затиранием)
        print(что)
    elif args.без_слежения:
        пути = [None] * len(области)
    else:
        пути = []
        for н, о in enumerate(области, 1):
            п = вести_шаблоном(кадры, о)
            пути.append(п)
            print("рамка %d ведётся шаблоном: начало %s, конец %s"
                  % (н, п[0], п[-1]))
    H, W = кадры[0].shape[:2]
    готовые = []
    for i, к in enumerate(кадры):
        if приём == "знак":
            готовые.append(снятие(к))
            continue
        н = к
        for о, путь in zip(области, пути):
            р = о if путь is None else tuple(
                v/(W if j % 2 == 0 else H) for j, v in enumerate(путь[i]))
            н = правка(н, р)
        готовые.append(н)
    куда = (ф.parent / ("проба-" + ф.name)) if args.проба else (
        Path(str(ф) + ".новый.mp4"))
    записать_клип(готовые, фпс, куда)
    a, b = длительность(ф), длительность(куда)
    if abs(a-b) > 0.06:
        куда.unlink(missing_ok=True)
        raise SystemExit("длина разошлась: %.2f -> %.2f, правка отменена" % (a, b))
    if args.проба:
        print("проба:", куда, "— %.2f с" % b)
        return
    запас.mkdir(parents=True, exist_ok=True)
    (запас / ф.name).write_bytes(ф.read_bytes())
    куда.replace(ф)
    print("правка внесена (%d кадров, %.2f с), оригинал в %s"
          % (len(готовые), b, запас))
    _сбросить_кэш(ф)
