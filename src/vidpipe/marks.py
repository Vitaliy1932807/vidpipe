"""Убрать из кадра то, чего там быть не должно: надписи и знак генератора.

Три приёма, каждый под свой случай. Выбор не вкусовой, он проверен на браке:

  затирание   маска по самим штрихам букв, потом inpaint. Идеально для
              надписи на ровной стене: заплатка берётся вплотную, границы
              не видно. На мелкой табличке растворяет саму табличку.

  сглаживание сжатие контраста внутри рамки. Буквы тонут, предмет остаётся
              резким и на месте. Для табличек и щитов лучше расфокуса: не
              появляется мягкий блок, табличка читается как выцветшая.
              Крупный текст так не убрать — размытая основа сохраняет его
              как свечение, там нужно затирание.

  знак        водяной знак генератора: постоянное место, маленькая область.
              Снимается накладкой — обратным альфа-смешением, см. veo.py:
              под знаком возвращается настоящая картинка, а не заплатка.
              Затирание осталось запасным ходом на случай, когда знак не
              опознан: оно работает всегда, но оставляет в углу мыло.

Сопровождение. Общая модель движения кадра (ORB) на бликах и дымке врёт и
об этом молчит: возвращает преобразование, просто неверное. Поэтому рамку
ведёт шаблон самого предмета с подбором масштаба — он следит ровно за тем,
что надо закрыть, и переживает наезд.
"""
from __future__ import annotations

